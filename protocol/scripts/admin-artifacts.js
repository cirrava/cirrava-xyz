// Writes ../app/admin-artifacts.js: the ABI + creation bytecode of StockOracle and LendingMarket (from this
// repo's compiled artifacts, the same build that is verified on Sourcify) and the markets to add, so the
// owner can deploy new markets from the browser with their own wallet at /app/admin.
//   npx hardhat compile && node scripts/admin-artifacts.js
//   MARKETS_JSON=path/to/markets.json node scripts/admin-artifacts.js   (override, e.g. for a local test chain)
const fs = require("fs");
const path = require("path");
const A = require("./mainnet-assets");

const art = (name) => {
  const j = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "artifacts", "contracts", `${name}.sol`, `${name}.json`), "utf8"));
  return { abi: j.abi, bytecode: j.bytecode };
};
const markets = process.env.MARKETS_JSON ? JSON.parse(fs.readFileSync(process.env.MARKETS_JSON, "utf8")) : A.newMarkets;
const bi = path.join(__dirname, "..", "artifacts", "build-info");
const out = {
  build: fs.readdirSync(bi)[0].replace(/\.json$/, ""),
  newMarkets: markets,
  params: { inSessionMaxAge: 26 * 3600, hardMaxAge: 97 * 3600, liquidationBonus: 0.05, reserveFactor: 0.1, borrowFee: 0.001 },
  StockOracle: art("StockOracle"),
  LendingMarket: art("LendingMarket"),
};
const file = path.join(__dirname, "..", "..", "app", "admin-artifacts.js");
fs.writeFileSync(file, `// Generated by protocol/scripts/admin-artifacts.js — do not edit by hand.\nwindow.CIRRAVA_ADMIN = ${JSON.stringify(out)};\n`);
console.log(`Wrote ${path.relative(process.cwd(), file)} (${(fs.statSync(file).size / 1024).toFixed(0)} KB, build ${out.build}, markets ${markets.map((m) => m.symbol).join(", ")})`);
