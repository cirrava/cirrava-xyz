// Writes ../app/deployment.js (what the web app reads) from a deployment record.
//   node scripts/app-config.js robinhood        → from deployments/robinhood.json
const fs = require("fs");
const path = require("path");

function writeAppConfig(dep) {
  const cfg = {
    ...dep,
    // Browsers read the chain through cirrava.xyz/rpc (nginx proxy), so visitors whose ISP blocks the
    // public RPC still see live data. Wallet transactions go through the wallet's own RPC.
    readRpc: dep.chainId === 31337 ? undefined : "/rpc",
  };
  const dir = path.join(__dirname, "..", "..", "app");
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, "deployment.js");
  fs.writeFileSync(file, `// Generated by protocol/scripts — do not edit by hand.\nwindow.CIRRAVA_DEPLOYMENT = ${JSON.stringify(cfg, null, 2)};\n`);
  console.log(`Wrote ${path.relative(process.cwd(), file)}`);
}

if (require.main === module) {
  const name = process.argv[2] || "robinhood";
  const dep = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "deployments", `${name}.json`), "utf8"));
  writeAppConfig(dep);
}

module.exports = { writeAppConfig };
